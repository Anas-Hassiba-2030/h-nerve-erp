// scripts/build/build-voac-skills.mjs
//
// Compiles src/lib/voac/skills/*.md into src/lib/voac/skills.generated.ts.
//
// WHY A BUILD STEP AT ALL: the skill documents must stay real .md files,
// because that is the artifact Microsoft SkillOpt trains — it reads a markdown
// document, proposes bounded add/delete/replace edits against scored rollouts,
// and writes back a best_skill.md. Inline TypeScript template literals would
// have nothing for it to train. But the app runs on Cloudflare Workers, which
// has no filesystem at request time, so the docs cannot be read at runtime
// either. Compiling .md → .ts satisfies both: SkillOpt owns the markdown, the
// Worker ships a plain module.
//
// Same shape as scripts/build/build-orrery.mjs — source of truth is the
// authored file, the generated artifact is committed and never hand-edited.
//
//   node scripts/build/build-voac-skills.mjs

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SKILLS_DIR = resolve(here, "../../src/lib/voac/skills");
const OUT_FILE = resolve(here, "../../src/lib/voac/skills.generated.ts");

/** Short content hash — this becomes AgentRun.skillVersion, so a score can be
 *  attributed to the exact revision of the document that produced it. */
function version(body) {
  return createHash("sha256").update(body).digest("hex").slice(0, 8);
}

function build() {
  const files = readdirSync(SKILLS_DIR)
    .filter((f) => f.endsWith(".md"))
    .sort();

  if (files.length === 0) {
    throw new Error(`No skill documents found in ${SKILLS_DIR}`);
  }

  const entries = files.map((file) => {
    const id = file.replace(/\.md$/, "");
    const body = readFileSync(join(SKILLS_DIR, file), "utf8");
    return { id, body, version: version(body) };
  });

  const lines = [
    "// AUTO-GENERATED by scripts/build/build-voac-skills.mjs — DO NOT EDIT.",
    "// Edit the markdown in src/lib/voac/skills/ and re-run the script.",
    "// (SkillOpt writes to those .md files; this module is what the Worker ships.)",
    "",
    "export type SkillDoc = {",
    "  id: string;",
    "  /** Content hash of the document — recorded as AgentRun.skillVersion. */",
    "  version: string;",
    "  body: string;",
    "};",
    "",
    "export const SKILL_DOCS: Record<string, SkillDoc> = {",
  ];

  for (const e of entries) {
    lines.push(`  ${JSON.stringify(e.id)}: {`);
    lines.push(`    id: ${JSON.stringify(e.id)},`);
    lines.push(`    version: ${JSON.stringify(e.version)},`);
    lines.push(`    body: ${JSON.stringify(e.body)},`);
    lines.push("  },");
  }

  lines.push("};");
  lines.push("");

  writeFileSync(OUT_FILE, lines.join("\n"), "utf8");
  console.log(`[voac] compiled ${entries.length} skill document(s) -> ${OUT_FILE}`);
  for (const e of entries) console.log(`  ${e.id} @ ${e.version} (${e.body.length} chars)`);
}

build();
