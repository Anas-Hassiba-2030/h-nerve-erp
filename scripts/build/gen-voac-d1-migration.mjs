// scripts/build/gen-voac-d1-migration.mjs
//
// Generates AND REHEARSES the D1 migration that adds the VOAC schema to an
// existing production database.
//
// It does two things, and the second is the point:
//
//   1. Emits prisma/migrations-d1/2026-08-04-voac.sql from the local dev
//      database's own sqlite_master — so the SQL is exactly what Prisma
//      actually created, not something hand-written that drifts from it.
//   2. REHEARSES it against a throwaway COPY of a pre-VOAC snapshot
//      (prisma/dev.db), then asserts the tables landed AND that the existing
//      rows are untouched.
//
// Rehearsal matters because D1 has no interactive transactions: a migration
// that fails halfway leaves the database half-migrated with no rollback. The
// only honest way to know it applies cleanly is to apply it somewhere real
// first. Production is not that place.
//
// This script NEVER touches production. It writes a .sql file and a scratch
// copy, and prints the command a human runs when they decide to.
//
//   node scripts/build/gen-voac-d1-migration.mjs

import { DatabaseSync } from "node:sqlite";
import { copyFileSync, mkdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, "../..");

const SOURCE_DB = join(ROOT, "dev.db");                    // has the VOAC schema
const PRE_VOAC_DB = join(ROOT, "prisma/dev.db");           // older snapshot, no VOAC
const OUT_DIR = join(ROOT, "prisma/migrations-d1");
const OUT_SQL = join(OUT_DIR, "2026-08-04-voac.sql");
const SCRATCH = join(ROOT, "prisma/.voac-migration-rehearsal.db");

const VOAC_TABLES = ["VoacRoster", "AgentRun", "AgentStep", "AgentProposal"];

// Additive column adds on an EXISTING table. Listed explicitly rather than
// diffed, because a generated column diff that guesses wrong on a live ERP is
// how you drop a column you meant to keep.
const COLUMN_ADDS = [
  { table: "DairyBatch", column: "pricePerLiter", type: "REAL" },
  { table: "DairyBatch", column: "costPerLiter", type: "REAL" },
];

function buildSql() {
  const db = new DatabaseSync(SOURCE_DB);
  const objs = db
    .prepare(
      `select type, name, sql from sqlite_master
       where tbl_name in (${VOAC_TABLES.map(() => "?").join(",")})
         and sql is not null
       order by case type when 'table' then 0 else 1 end, name`,
    )
    .all(...VOAC_TABLES);

  const lines = [
    "-- VOAC schema — additive D1 migration.",
    "-- Generated by scripts/build/gen-voac-d1-migration.mjs from the local dev",
    "-- database's own sqlite_master. Do not hand-edit; regenerate instead.",
    "--",
    "-- ADDITIVE ONLY: four new tables, their indexes, and two nullable columns",
    "-- on DairyBatch. No DROP, no ALTER of an existing column, no data rewrite.",
    "-- Existing rows are untouched.",
    "--",
    "-- D1 has no interactive transactions, so a failure part-way leaves the",
    "-- database half-migrated. Every statement below is IF NOT EXISTS so a",
    "-- re-run after a partial failure is safe.",
    "",
  ];

  for (const o of objs) {
    // Prisma emits plain CREATE TABLE / CREATE INDEX; make them idempotent.
    let sql = o.sql.trim();
    sql = sql.replace(/^CREATE TABLE\s+/i, "CREATE TABLE IF NOT EXISTS ");
    sql = sql.replace(/^CREATE INDEX\s+/i, "CREATE INDEX IF NOT EXISTS ");
    sql = sql.replace(/^CREATE UNIQUE INDEX\s+/i, "CREATE UNIQUE INDEX IF NOT EXISTS ");
    lines.push(sql.endsWith(";") ? sql : sql + ";");
  }

  lines.push("");
  lines.push("-- Nullable on purpose: an un-entered price must stay visibly");
  lines.push("-- un-entered, never read as zero recoverable value.");
  for (const c of COLUMN_ADDS) {
    lines.push(`ALTER TABLE "${c.table}" ADD COLUMN "${c.column}" ${c.type};`);
  }
  lines.push("");

  return { sql: lines.join("\n"), objectCount: objs.length };
}

function rehearse(sql) {
  if (!existsSync(PRE_VOAC_DB)) {
    console.log(`\n⚠ No pre-VOAC snapshot at ${PRE_VOAC_DB} — rehearsal SKIPPED.`);
    return false;
  }

  rmSync(SCRATCH, { force: true });
  copyFileSync(PRE_VOAC_DB, SCRATCH);
  const db = new DatabaseSync(SCRATCH);

  const before = {};
  for (const t of ["Company", "DairyBatch", "Transaction"]) {
    try {
      before[t] = db.prepare(`select count(*) c from "${t}"`).get().c;
    } catch {
      before[t] = null;
    }
  }

  // ALTER on a table that does not exist in this old snapshot would abort the
  // rehearsal for the wrong reason; report it rather than pretending.
  // Strip `--` line comments BEFORE splitting on `;`. Splitting first lets a
  // multi-line comment block bleed into the following statement, which then
  // fails to parse for a reason that has nothing to do with the migration.
  const executable = sql
    .split("\n")
    .filter((line) => !line.trim().startsWith("--"))
    .join("\n");

  let applied = 0;
  for (const stmt of executable.split(";").map((s) => s.trim()).filter(Boolean)) {
    try {
      db.exec(stmt + ";");
      applied += 1;
    } catch (e) {
      const msg = String(e.message || e);
      if (/duplicate column name/i.test(msg)) continue; // already additive-applied
      if (/no such table: main\.DairyBatch|no such table: DairyBatch/i.test(msg)) {
        console.log(`  (snapshot predates DairyBatch — column add not exercised)`);
        continue;
      }
      throw new Error(`Rehearsal FAILED on:\n${stmt.slice(0, 160)}\n→ ${msg}`);
    }
  }

  const created = db
    .prepare(
      `select name from sqlite_master where type='table' and name in (${VOAC_TABLES.map(() => "?").join(",")})`,
    )
    .all(...VOAC_TABLES)
    .map((r) => r.name);

  const after = {};
  for (const t of Object.keys(before)) {
    try {
      after[t] = db.prepare(`select count(*) c from "${t}"`).get().c;
    } catch {
      after[t] = null;
    }
  }

  console.log(`\n--- REHEARSAL on a copy of ${PRE_VOAC_DB} ---`);
  console.log(`  statements applied : ${applied}`);
  console.log(`  tables created     : ${created.sort().join(", ") || "none"}`);

  let intact = true;
  for (const t of Object.keys(before)) {
    if (before[t] === null) continue;
    const same = before[t] === after[t];
    if (!same) intact = false;
    console.log(`  ${t.padEnd(14)} rows ${before[t]} → ${after[t]}  ${same ? "unchanged ✓" : "CHANGED ✗"}`);
  }

  const allCreated = VOAC_TABLES.every((t) => created.includes(t));

  // Close before deleting: on Windows an open handle makes rmSync throw EPERM,
  // which would fail the script AFTER a perfectly good rehearsal.
  db.close();
  rmSync(SCRATCH, { force: true });

  if (!allCreated) throw new Error("Rehearsal FAILED — not every VOAC table was created.");
  if (!intact) throw new Error("Rehearsal FAILED — existing row counts changed. This is NOT additive.");
  return true;
}

const { sql, objectCount } = buildSql();
mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_SQL, sql, "utf8");
console.log(`[voac-d1] wrote ${OUT_SQL}`);
console.log(`[voac-d1] ${objectCount} schema object(s) + ${COLUMN_ADDS.length} column add(s)`);

const rehearsed = rehearse(sql);

console.log("\n" + "=".repeat(68));
console.log(rehearsed ? "MIGRATION REHEARSED CLEANLY — additive, existing data intact." : "MIGRATION GENERATED (not rehearsed).");
console.log("=".repeat(68));
console.log("\nThis script did NOT touch production. When you decide to apply it:\n");
console.log("  npx wrangler d1 execute h-nerve-erp-db --remote \\");
console.log("    --file prisma/migrations-d1/2026-08-04-voac.sql\n");
console.log("Take a backup first (docs/RUNBOOK.md § D1 backup) — additive or not,");
console.log("a migration against a live client database deserves one.");
