// Emit the Hourani real-entity seed as idempotent SQL for the REMOTE D1
// database.
//
// WHY THIS EXISTS: scripts/_prisma.ts talks to a local `file:` SQLite database
// over @prisma/adapter-libsql — there is no Node path to production D1, which
// is only reachable through `wrangler d1 execute --remote`. Rather than
// hand-writing the SQL (and letting it drift from the TypeScript the moment
// either changes), this imports the SAME constants the seed uses and prints
// their SQL equivalent. One source of truth, two execution paths.
//
//   npx tsx --tsconfig tsconfig.scripts.json scripts/build/hourani-seed-to-d1.ts > out.sql
//   npx wrangler d1 execute h-nerve-erp-db --remote --file out.sql
//
// Every statement is idempotent: companies upsert on their unique `code`,
// hotels insert only WHERE NOT EXISTS, and the repoints are UPDATEs keyed on
// the old name, so a second run is a no-op.

import {
  COMPANIES,
  HOTELS,
  HOTEL_REMAP,
  FARM_REMAP,
  CROP_REMAP,
} from "../seed/seed-hourani-real";

/** SQLite string literal — doubles single quotes, NULL for null/undefined. */
function q(v: string | number | null | undefined): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  return `'${v.replace(/'/g, "''")}'`;
}

/** Company id lookup by code, as a scalar subquery. */
function co(code: string): string {
  return `(SELECT id FROM Company WHERE code = ${q(code)})`;
}

// Prisma generates cuids in the client; raw SQL has no such function, so new
// rows get a random hex id. Nothing reads an id's FORMAT — only its uniqueness.
const NEW_ID = "lower(hex(randomblob(16)))";

const out: string[] = [];
const now = "CURRENT_TIMESTAMP";

out.push("-- Generated by scripts/build/hourani-seed-to-d1.ts — do not hand-edit.");
out.push("-- Source of truth: scripts/seed/seed-hourani-real.ts + docs/HOURANI-GROUP-PROFILE.md");
out.push("");

out.push("-- ── Companies: upsert on the unique code ──────────────────────────");
for (const c of COMPANIES) {
  out.push(
    `INSERT INTO Company (id, code, name, nameEn, sector, country, city, foundedYear, employees, status, description, brandColor, ticker, createdAt, updatedAt)\n` +
      `VALUES (${NEW_ID}, ${q(c.code)}, ${q(c.name)}, ${q(c.nameEn)}, ${q(c.sector)}, ${q(c.country)}, ${q(c.city)}, ${q(c.foundedYear)}, 0, 'ACTIVE', ${q(c.description)}, ${q(c.brandColor)}, ${q(c.ticker)}, ${now}, ${now})\n` +
      `ON CONFLICT(code) DO UPDATE SET\n` +
      `  name = excluded.name, nameEn = excluded.nameEn, sector = excluded.sector,\n` +
      `  country = excluded.country, city = excluded.city, foundedYear = excluded.foundedYear,\n` +
      `  employees = excluded.employees, description = excluded.description,\n` +
      `  brandColor = excluded.brandColor, ticker = excluded.ticker, updatedAt = ${now};`,
  );
}

out.push("");
out.push("-- ── Repoint legacy hotels onto their real counterparts ────────────");
out.push("-- Renames rather than deletes, so every booking survives. Guarded by");
out.push("-- NOT EXISTS so a re-run cannot collide two properties into one row.");
for (const [oldName, to] of Object.entries(HOTEL_REMAP)) {
  out.push(
    `UPDATE Hotel SET name = ${q(to.name)}, companyId = ${co(to.toCompany)}\n` +
      `WHERE name = ${q(oldName)}\n` +
      `  AND NOT EXISTS (SELECT 1 FROM Hotel h2 WHERE h2.name = ${q(to.name)});`,
  );
}

out.push("");
out.push("-- ── Hotels: correct the facts, then create any that are missing ───");
for (const h of HOTELS) {
  out.push(
    `UPDATE Hotel SET companyId = ${co(h.companyCode)}, nameEn = ${q(h.nameEn)}, city = ${q(h.city)},\n` +
      `  country = ${q(h.country)}, starRating = ${h.starRating}, totalRooms = ${h.totalRooms},\n` +
      `  tier = ${q(h.tier)}, description = ${q(h.description)}, updatedAt = ${now}\n` +
      `WHERE name = ${q(h.name)};`,
  );
  out.push(
    `INSERT INTO Hotel (id, companyId, name, nameEn, city, country, tier, totalRooms, starRating, baselineADR, description, createdAt, updatedAt)\n` +
      `SELECT ${NEW_ID}, ${co(h.companyCode)}, ${q(h.name)}, ${q(h.nameEn)}, ${q(h.city)}, ${q(h.country)}, ${q(h.tier)}, ${h.totalRooms}, ${h.starRating}, 120, ${q(h.description)}, ${now}, ${now}\n` +
      `WHERE NOT EXISTS (SELECT 1 FROM Hotel WHERE name = ${q(h.name)});`,
  );
}

out.push("");
out.push("-- ── Farms: Loran's plots become the fodder fields they really are ─");
for (const [oldName, to] of Object.entries(FARM_REMAP)) {
  const sets = [
    `name = ${q(to.name)}`,
    `type = ${q(to.type)}`,
    ...(to.location ? [`location = ${q(to.location)}`] : []),
    ...(to.toCompany ? [`companyId = ${co(to.toCompany)}`] : []),
    `updatedAt = ${now}`,
  ];
  out.push(
    `UPDATE Farm SET ${sets.join(", ")}\n` +
      `WHERE name = ${q(oldName)}\n` +
      `  AND NOT EXISTS (SELECT 1 FROM Farm f2 WHERE f2.name = ${q(to.name)});`,
  );
}

out.push("");
out.push("-- ── Crops: vegetables become the fodder Loran actually grows ──────");
for (const [oldName, realName] of Object.entries(CROP_REMAP)) {
  out.push(`UPDATE Crop SET name = ${q(realName)}, updatedAt = ${now} WHERE name = ${q(oldName)};`);
}

console.log(out.join("\n"));
