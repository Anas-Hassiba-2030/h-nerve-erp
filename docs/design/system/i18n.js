window.HNi18n = (function(){
  var KEY="hnerve_lang";
  function lang(){ try{ return localStorage.getItem(KEY)||"ar"; }catch(e){ return "ar"; } }
  function t(key,l){ l=l||lang(); var s=HN_STRINGS[key]; return s?(s[l]||s.ar):key; }
  function apply(root){ root=root||document;
    var l=lang();
    root.querySelectorAll("[data-i18n]").forEach(function(el){
      var k=el.getAttribute("data-i18n"); var s=HN_STRINGS[k]; if(!s) return;
      var v=s[l]||s.ar;
      if(el.hasAttribute("data-i18n-attr")){ el.setAttribute(el.getAttribute("data-i18n-attr"), v); }
      else el.textContent=v;
    });
  }
  function set(l){
    try{ localStorage.setItem(KEY,l); }catch(e){}
    document.documentElement.setAttribute("lang",l);
    document.documentElement.setAttribute("dir", l==="ar"?"rtl":"ltr");
    apply(document);
    document.querySelectorAll(".tb-lang .lang-opt,.lang-opt").forEach(function(o){ o.classList.toggle("on",o.dataset.l===l); });
    try{ window.dispatchEvent(new CustomEvent("hn-lang",{detail:{lang:l}})); }catch(e){}
  }
  function toggle(){ set(lang()==="ar"?"en":"ar"); }
  // reverse index: arabic literal → key (built once), and tr() translates an AR string to active lang
  var REV=null;
  function buildRev(){ REV={}; for(var k in HN_STRINGS){ var ar=HN_STRINGS[k].ar; if(ar!=null) REV[ar]=k; } }
  function tr(s,l){ if(s==null) return s; if(!REV) buildRev(); var k=REV[(""+s).trim()]; if(!k) return s; l=l||lang(); var o=HN_STRINGS[k]; return o?(o[l]||o.ar):s; }
  // engine re-render registry: pages register a render fn; fired on language change
  function onChange(fn){ if(typeof fn==="function") window.addEventListener("hn-lang",function(){ try{ fn(lang()); }catch(e){} }); }
  function init(){ var l=lang(); document.documentElement.setAttribute("lang",l); document.documentElement.setAttribute("dir",l==="ar"?"rtl":"ltr"); apply(document);
    document.querySelectorAll(".tb-lang .lang-opt,.lang-opt").forEach(function(o){ o.classList.toggle("on",o.dataset.l===l); }); }
  return { t:t, set:set, toggle:toggle, apply:apply, init:init, lang:lang, tr:tr, onChange:onChange };
})();
